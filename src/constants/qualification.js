export function xgTarget(opt) {
  const s = xgScore(opt.lv, opt.gate2, opt.gate2me, '');
  const items = s.cats[0].items.filter(x => !x.sum);
  const total = items.reduce((a, x) => a + (x.score || 0), 0);
  /* 硬门槛有「不符合」的档位不出材料分（与职称 / 称号口径一致） */
  const blocked = (opt.gates || []).some(g => g.rows.some(r => r.j === 'no'));
  return {
    name: opt.name, ver: opt.ver, rec: opt.rec, kind: opt.kind, docs: XG_DOCS, gateGroups: opt.gates,
    score: blocked ? null : { total: +total.toFixed(1), full: null, cats: s.cats }, ai: opt.ai, fixPath: opt.fixPath
  };
}

